let val = 1;
console.log((val == 1) && (val == true)) // El && significa Y, asi que si val es 1 y es verdadero funcionara
console.log((val == 1) || (val == true)) // El || significa O asi que si val es 1 o verdadero funcionara
console.log(!val) // El ! significa contrario de asi que nos da lo contrario a lo que nos daria, en este caso nos dara un falso