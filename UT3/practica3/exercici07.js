console.log(5 == "5") // Es true porque es 5 si se convierte en number
console.log(5 === "5") // Es false porque "5" es un string y 5 un number
console.log(0 == false) // Es true porque 0 y false si se convierten son lo mismo
console.log(0 === false) // Es false porque 0 y false no son lo mismo

// La diferencia entre == y === es que el === es mas restricto y comprueba sin comversiones